// OldTweetDeck_jp: per-column automatic tweet translation.
//
// Loaded by src/injection.js from the extension package (see src/custom/scripts.json),
// so it is never overwritten by the remote interception.js / bundle.js updates.
//
// - Adds a "翻訳 OFF/ON" toggle button to every column header (left of the settings icon). Translation runs only in columns
//   where it is switched on (stored in localStorage.OTDjpTranslateColumns).
// - Prefers the Grok translations X already embeds in timeline responses
//   (grok_translated_post_with_availability), the same ones x.com shows in lists.
// - Falls back to TweetDeck's own translateTweet() -> /1.1/translations/show.json, which
//   interception.js proxies to X's translation service (the same one behind "Translate post").
// - Every result is cached in localStorage.OTDjpTranslateCache, so a tweet is translated once.
(function () {
    "use strict";

    const COLUMNS_KEY = "OTDjpTranslateColumns";
    const CACHE_KEY = "OTDjpTranslateCache";
    const TARGET_KEY = "OTDjpTranslateTarget";
    const HINT_KEY = "OTDjpTranslateHintShown";
    const CACHE_MAX = 3000;
    const CONCURRENCY = 2;
    const REQUEST_INTERVAL = 400;
    const RETRY_AFTER = 5 * 60 * 1000;
    const ERROR_BACKOFF = 30 * 1000;
    // undetermined / no linguistic content / media-only / hashtag-only etc.
    const SKIP_LANGS = new Set(["", "und", "zxx", "qme", "qam", "qct", "qht", "qhm", "qst", "art"]);

    const baseLang = lang => (lang || "").toLowerCase().split("-")[0];
    const targetLang = () => baseLang(localStorage.getItem(TARGET_KEY) || "ja");

    function readJSON(key, fallback) {
        try {
            const value = localStorage.getItem(key);
            return value ? JSON.parse(value) : fallback;
        } catch (e) {
            console.warn(`[OTDjp] failed to read ${key}`, e);
            return fallback;
        }
    }

    // ---- enabled columns ----
    // The DOM column key (data-column="c<timestamp>…") is regenerated by TweetDeck on every load,
    // so the setting is stored under the column's persistent id ("api:<apiid>", the id OldTweetDeck
    // keeps in localStorage.OTDcolumns). A DOM key is stored only until the column gets its apiid.

    // DOM keys saved by a previous page load can never match again; drop them.
    const enabledColumns = new Set(readJSON(COLUMNS_KEY, []).filter(id => String(id).startsWith("api:")));
    function saveColumns() {
        try {
            localStorage.setItem(COLUMNS_KEY, JSON.stringify([...enabledColumns]));
        } catch (e) {
            console.warn("[OTDjp] failed to save columns", e);
        }
    }

    function persistentId(key) {
        try {
            const column = TD.controller.columnManager.get(key);
            const model = column && column.model;
            if (model && typeof model.getApiid === "function" && (!model.hasApiid || model.hasApiid())) {
                const apiid = model.getApiid();
                if (apiid) return `api:${apiid}`;
            }
        } catch (e) {}
        return null;
    }

    function isEnabled(key) {
        const id = persistentId(key);
        if (id && enabledColumns.has(id)) return true;
        if (!enabledColumns.has(key)) return false;
        if (id) {
            // enabled before the column was synced: move the setting to its persistent id
            enabledColumns.delete(key);
            enabledColumns.add(id);
            saveColumns();
        }
        return true;
    }

    function setEnabled(key, on) {
        const id = persistentId(key);
        enabledColumns.delete(key);
        if (id) enabledColumns.delete(id);
        if (on) enabledColumns.add(id || key);
        saveColumns();
    }

    // ---- cache ----
    // key: `${targetLang}:${tweetId}` -> { h: translated html, l: source lang, t: last used }
    //                                  | { n: 1, t } (no translation needed)

    let cache = readJSON(CACHE_KEY, {});
    if (typeof cache !== "object" || cache === null || Array.isArray(cache)) cache = {};
    let saveTimer = null;

    function pruneCache(max) {
        const keys = Object.keys(cache);
        if (keys.length <= max) return;
        keys.sort((a, b) => (cache[a].t || 0) - (cache[b].t || 0));
        for (const key of keys.slice(0, keys.length - Math.floor(max * 2 / 3))) {
            delete cache[key];
        }
    }

    function saveCache() {
        clearTimeout(saveTimer);
        saveTimer = setTimeout(() => {
            pruneCache(CACHE_MAX);
            try {
                localStorage.setItem(CACHE_KEY, JSON.stringify(cache));
            } catch (e) {
                // quota exceeded: shrink and retry once
                pruneCache(Math.floor(Object.keys(cache).length / 2));
                try {
                    localStorage.setItem(CACHE_KEY, JSON.stringify(cache));
                } catch (e2) {
                    console.warn("[OTDjp] failed to save translation cache", e2);
                }
            }
        }, 2000);
    }

    // ---- translation requests ----

    const queue = [];
    const queued = new Set();
    const failed = new Map();
    let active = 0;
    let pausedUntil = 0;

    function escapeHtml(text) {
        const div = document.createElement("div");
        div.textContent = text;
        return div.innerHTML;
    }

    function renderHtml(text, entities) {
        try {
            return window.TD.util.transform(text, entities || {});
        } catch (e) {
            return escapeHtml(text);
        }
    }

    function fetchTranslation(id, lang) {
        return new Promise((resolve, reject) => {
            const client = TD.controller.clients.getPreferredClient("twitter");
            if (!client) return reject(new Error("no twitter client"));
            client.translateTweet(id, lang, resolve, reject);
        });
    }

    function enqueue(id, key) {
        if (queued.has(key)) return;
        queued.add(key);
        queue.push({ id, key, lang: targetLang() });
        pump();
    }

    function pump() {
        while (active < CONCURRENCY && queue.length) {
            const wait = pausedUntil - Date.now();
            if (wait > 0) {
                setTimeout(pump, wait);
                return;
            }
            const job = queue.shift();
            active++;
            fetchTranslation(job.id, job.lang)
                .then(res => {
                    if (!res || !res.text || baseLang(res.translated_lang) === job.lang) {
                        cache[job.key] = { n: 1, t: Date.now() };
                    } else {
                        cache[job.key] = {
                            h: renderHtml(res.text, res.entities),
                            l: res.translated_lang,
                            t: Date.now(),
                        };
                    }
                    failed.delete(job.key);
                    saveCache();
                })
                .catch(e => {
                    console.warn(`[OTDjp] translation failed for ${job.id}`, e);
                    failed.set(job.key, Date.now());
                    pausedUntil = Date.now() + ERROR_BACKOFF;
                })
                .finally(() => {
                    queued.delete(job.key);
                    resolvePending(job.key);
                    setTimeout(() => {
                        active--;
                        pump();
                    }, REQUEST_INTERVAL);
                });
        }
    }

    // ---- DOM ----

    let languageNames = null;
    try {
        languageNames = new Intl.DisplayNames(["ja"], { type: "language" });
    } catch (e) {}
    const languageName = lang => {
        try {
            return (languageNames && languageNames.of(lang)) || lang;
        } catch (e) {
            return lang;
        }
    };

    function columnElement(key) {
        return document.querySelector(`.js-app-columns .js-column[data-column="${CSS.escape(key)}"]`);
    }

    function isInEnabledColumn(el) {
        const column = el.closest(".js-app-columns .js-column[data-column]");
        return !!column && isEnabled(column.getAttribute("data-column"));
    }

    function applyTranslation(el, entry) {
        el.__otdjpOriginal = el.innerHTML;
        el.innerHTML = entry.h;
        el.dataset.otdjpState = "translated";

        const note = document.createElement("div");
        note.className = "otdjp-translate-note";
        note.innerHTML = `${escapeHtml(languageName(entry.l))}から翻訳${entry.g ? "（Grok）" : ""} · <a href="#" class="otdjp-translate-toggle">原文を表示</a>`;
        el.insertAdjacentElement("afterend", note);
    }

    function restoreOriginal(el) {
        if (el.dataset.otdjpState === "translated" && el.__otdjpOriginal !== undefined) {
            el.innerHTML = el.__otdjpOriginal;
            const note = el.nextElementSibling;
            if (note && note.classList.contains("otdjp-translate-note")) note.remove();
        }
        delete el.__otdjpOriginal;
        delete el.dataset.otdjpState;
        delete el.dataset.otdjpKey;
    }

    function resolvePending(key) {
        const els = document.querySelectorAll(`.js-tweet-text[data-otdjp-state="pending"][data-otdjp-key="${CSS.escape(key)}"]`);
        const entry = cache[key];
        for (const el of els) {
            if (!entry) {
                // failed: leave unmarked so a later scan can retry after RETRY_AFTER
                delete el.dataset.otdjpState;
            } else if (entry.n) {
                el.dataset.otdjpState = "skip";
            } else if (isInEnabledColumn(el)) {
                applyTranslation(el, entry);
            } else {
                delete el.dataset.otdjpState;
            }
        }
    }

    function processTweetText(el) {
        const lang = baseLang(el.getAttribute("lang"));
        const target = targetLang();
        const holder = el.closest("[data-tweet-id]");
        const id = holder && holder.getAttribute("data-tweet-id");
        if (SKIP_LANGS.has(lang) || lang === target || !id || !el.textContent.trim()) {
            el.dataset.otdjpState = "skip";
            return;
        }
        const key = `${target}:${id}`;
        const entry = cache[key];
        if (entry) {
            entry.t = Date.now();
            if (entry.n) {
                el.dataset.otdjpState = "skip";
            } else {
                applyTranslation(el, entry);
            }
            return;
        }
        const failedAt = failed.get(key);
        if (failedAt && Date.now() - failedAt < RETRY_AFTER) return;
        el.dataset.otdjpState = "pending";
        el.dataset.otdjpKey = key;
        enqueue(id, key);
    }

    function updateButton(btn, key) {
        const on = isEnabled(key);
        btn.classList.toggle("is-active", on);
        btn.textContent = on ? "翻訳 ON" : "翻訳 OFF";
        btn.title = on
            ? "このカラムの自動翻訳: オン（クリックでオフ）"
            : "このカラムの自動翻訳: オフ（クリックでオン）";
    }

    function ensureButtons() {
        for (const column of document.querySelectorAll(".js-app-columns .js-column[data-column]")) {
            const links = column.querySelector(".column-header-links");
            if (!links) continue;
            const key = column.getAttribute("data-column");
            const existing = links.querySelector(".otdjp-translate-btn");
            if (existing) {
                if (existing.classList.contains("is-active") !== isEnabled(key)) updateButton(existing, key);
                continue;
            }
            const btn = document.createElement("a");
            btn.href = "#";
            btn.className = "otdjp-translate-btn";
            btn.addEventListener("click", e => {
                e.preventDefault();
                e.stopPropagation();
                toggleColumn(key);
            });
            updateButton(btn, key);
            links.insertBefore(btn, links.firstChild);
        }
    }

    function scan() {
        ensureButtons();
        for (const column of document.querySelectorAll(".js-app-columns .js-column[data-column]")) {
            if (!isEnabled(column.getAttribute("data-column"))) continue;
            for (const el of column.querySelectorAll(".js-tweet-text:not([data-otdjp-state])")) {
                processTweetText(el);
            }
        }
    }

    let scanTimer = null;
    function scheduleScan() {
        if (scanTimer) return;
        scanTimer = setTimeout(() => {
            scanTimer = null;
            scan();
        }, 50);
    }

    function toggleColumn(key, force) {
        const on = force === undefined ? !isEnabled(key) : !!force;
        setEnabled(key, on);

        const column = columnElement(key);
        if (column) {
            const btn = column.querySelector(".otdjp-translate-btn");
            if (btn) updateButton(btn, key);
            if (!on) {
                for (const el of column.querySelectorAll(".js-tweet-text[data-otdjp-state]")) {
                    restoreOriginal(el);
                }
            }
        }
        scheduleScan();
    }

    // "原文を表示" / "翻訳を表示"
    document.addEventListener("click", e => {
        const toggle = e.target.closest && e.target.closest(".otdjp-translate-toggle");
        if (!toggle) return;
        e.preventDefault();
        e.stopPropagation();
        const note = toggle.closest(".otdjp-translate-note");
        const el = note && note.previousElementSibling;
        if (!el || el.__otdjpOriginal === undefined) return;
        const showingOriginal = toggle.dataset.showing === "original";
        const translated = el.__otdjpTranslated || el.innerHTML;
        if (showingOriginal) {
            el.innerHTML = translated;
            toggle.textContent = "原文を表示";
            toggle.dataset.showing = "translated";
        } else {
            el.__otdjpTranslated = el.innerHTML;
            el.innerHTML = el.__otdjpOriginal;
            toggle.textContent = "翻訳を表示";
            toggle.dataset.showing = "original";
        }
    }, true);

    // Make X translate into the requested `dest` language instead of the browser language.
    // Wraps the route defined in interception.js without editing that (remotely updated) file.
    function patchTranslationRoute() {
        try {
            if (typeof proxyRoutes === "undefined") return;
            const route = proxyRoutes.find(r => r && r.path === "/1.1/translations/show.json");
            if (!route || route.__otdjpPatched) return;
            const original = route.beforeSendHeaders;
            route.beforeSendHeaders = function (xhr) {
                if (original) original.call(this, xhr);
                try {
                    const dest = new URL(xhr.originalUrl, location.href).searchParams.get("dest");
                    if (dest) xhr.modReqHeaders["X-Twitter-Client-Language"] = dest;
                } catch (e) {}
            };
            route.__otdjpPatched = true;
        } catch (e) {
            console.warn("[OTDjp] failed to patch translation route", e);
        }
    }

    // ---- Grok translations delivered inside timeline responses ----
    // x.com asks for them with the `responsive_web_grok_show_grok_translated_post` feature flag and
    // receives them per tweet as `grok_translated_post_with_availability`:
    //   { is_available, data: { translation, entities, source_language, destination_language } }
    // They are stored in the same cache, so no per-tweet translation request is needed.

    const GROK_FLAG = "responsive_web_grok_show_grok_translated_post";
    const GROK_KEY = "grok_translated_post_with_availability";
    let grokHits = 0;

    function enableGrokFlag(xhr) {
        const url = new URL(xhr.modUrl, location.href);
        const features = url.searchParams.get("features");
        if (!features || !features.includes(GROK_FLAG)) return;
        const parsed = JSON.parse(features);
        parsed[GROK_FLAG] = true;
        url.searchParams.set("features", JSON.stringify(parsed));
        xhr.modUrl = url.toString();
        xhr.__otdjpGrok = true;
    }

    // Media links (t.co) are hidden by TweetDeck in the original text; drop them from the translation too.
    function stripMediaUrls(text, legacy) {
        const media = (legacy && legacy.entities && legacy.entities.media) || [];
        for (const m of media) {
            if (m && m.url) text = text.split(m.url).join("");
        }
        return text.trim();
    }

    function harvestGrok(xhr) {
        if (xhr.__otdjpHarvested) return;
        xhr.__otdjpHarvested = true;
        const text = xhr.responseText;
        if (!text || !text.includes(GROK_KEY)) return;
        const target = targetLang();
        const stored = [];
        const stack = [JSON.parse(text)];
        while (stack.length) {
            const node = stack.pop();
            if (!node || typeof node !== "object") continue;
            const grok = node[GROK_KEY];
            if (grok && grok.is_available && grok.data && grok.data.translation) {
                const id = node.rest_id || (node.legacy && node.legacy.id_str);
                const data = grok.data;
                if (id && baseLang(data.destination_language) === target) {
                    const key = `${target}:${id}`;
                    if (baseLang(data.source_language) === target) {
                        cache[key] = { n: 1, t: Date.now() };
                    } else {
                        cache[key] = {
                            h: renderHtml(stripMediaUrls(data.translation, node.legacy), data.entities),
                            l: data.source_language,
                            g: 1,
                            t: Date.now(),
                        };
                    }
                    stored.push(key);
                }
            }
            for (const key in node) {
                const value = node[key];
                if (value && typeof value === "object") stack.push(value);
            }
        }
        if (!stored.length) return;
        grokHits += stored.length;
        saveCache();
        for (const key of stored) resolvePending(key);
        scheduleScan();
    }

    // Wraps the routes of interception.js (without editing that remotely updated file) so that
    // every GraphQL timeline request asks for Grok translations and its response is harvested.
    function patchGrokRoutes() {
        try {
            if (typeof proxyRoutes === "undefined") return;
            for (const route of proxyRoutes) {
                if (!route || route.__otdjpGrok) continue;
                route.__otdjpGrok = true;
                const before = route.beforeRequest;
                if (before) {
                    route.beforeRequest = function (xhr) {
                        before.call(this, xhr);
                        try { enableGrokFlag(xhr); } catch (e) {}
                    };
                }
                const headers = route.beforeSendHeaders;
                if (headers) {
                    route.beforeSendHeaders = function (xhr) {
                        headers.call(this, xhr);
                        if (xhr.__otdjpGrok) xhr.modReqHeaders["X-Twitter-Client-Language"] = targetLang();
                    };
                }
                const after = route.afterRequest;
                if (after) {
                    route.afterRequest = function (xhr) {
                        try {
                            if (!(xhr.storage && xhr.storage.cancelled)) harvestGrok(xhr);
                        } catch (e) {
                            console.warn("[OTDjp] failed to read Grok translations", e);
                        }
                        return after.call(this, xhr);
                    };
                }
            }
        } catch (e) {
            console.warn("[OTDjp] failed to patch routes for Grok translations", e);
        }
    }

    function injectStyle() {
        const style = document.createElement("style");
        style.textContent = `
            .otdjp-translate-btn {
                display: inline-block; vertical-align: middle; margin: 0 6px 0 4px; padding: 1px 7px;
                border: 1px solid #8899a6; border-radius: 10px;
                font-size: 11px; font-weight: bold; line-height: 16px; white-space: nowrap;
                color: #8899a6 !important; text-decoration: none !important; cursor: pointer;
            }
            .otdjp-translate-btn:hover { border-color: #1d9bf0; color: #1d9bf0 !important; }
            .otdjp-translate-btn.is-active { background: #1d9bf0; border-color: #1d9bf0; color: #fff !important; }
            .otdjp-hint {
                position: fixed; right: 16px; bottom: 16px; z-index: 10000; max-width: 360px;
                padding: 12px 14px; border-radius: 8px; background: #15202b; color: #fff;
                font-size: 13px; line-height: 19px; box-shadow: 0 4px 16px rgba(0,0,0,.4);
            }
            .otdjp-hint b { color: #1d9bf0; }
            .otdjp-hint button {
                margin-top: 8px; padding: 2px 10px; border: 0; border-radius: 10px;
                background: #1d9bf0; color: #fff; cursor: pointer;
            }
            .otdjp-translate-btn.is-flash { box-shadow: 0 0 0 3px #ffad1f; }
            .otdjp-translate-note { font-size: 12px; line-height: 16px; color: #8899a6; margin-top: 2px; }
            .otdjp-translate-note a { color: #1d9bf0; }
        `;
        document.head.appendChild(style);
    }

    // First-run hint that points at the header buttons.
    function showHint(force) {
        if (!force && localStorage.getItem(HINT_KEY)) return;
        const hint = document.createElement("div");
        hint.className = "otdjp-hint";
        hint.innerHTML = `<b>OldTweetDeck JP</b><br>各カラムの見出し右上（設定アイコンの左）にある
            <b>「翻訳 OFF」</b>ボタンを押すと、そのカラムの日本語以外のツイートが自動で翻訳されます。<br>
            <button type="button">わかった</button>`;
        hint.querySelector("button").addEventListener("click", () => {
            try { localStorage.setItem(HINT_KEY, "1"); } catch (e) {}
            hint.remove();
            flashButtons(false);
        });
        document.body.appendChild(hint);
        flashButtons(true);
    }

    function flashButtons(on) {
        for (const btn of document.querySelectorAll(".otdjp-translate-btn")) {
            btn.classList.toggle("is-flash", on);
        }
    }

    function init() {
        injectStyle();
        new MutationObserver(scheduleScan).observe(document.body, { childList: true, subtree: true });
        setInterval(scheduleScan, 30 * 1000);
        scan();
        showHint();
        console.log(`[OTDjp] OldTweetDeck JP auto-translate ready (${enabledColumns.size} column(s), ${Object.keys(cache).length} cached)`);
    }

    window.OTDjpTranslate = {
        enable: key => toggleColumn(key, true),
        disable: key => toggleColumn(key, false),
        columns: () => [...enabledColumns],
        hint: () => showHint(true),
        clearCache: () => {
            cache = {};
            saveCache();
        },
        stats: () => ({
            cached: Object.keys(cache).length,
            queued: queue.length,
            active,
            failed: failed.size,
            grok: grokHits,
            target: targetLang(),
        }),
    };

    // Patch the request routes right away so the first timeline requests already carry Grok translations.
    patchTranslationRoute();
    patchGrokRoutes();

    const readyTimer = setInterval(() => {
        if (window.TD && TD.ready && TD.controller && TD.controller.clients && TD.util && document.body) {
            clearInterval(readyTimer);
            init();
        }
    }, 500);
})();
